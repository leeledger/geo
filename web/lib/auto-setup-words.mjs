/** 한 낱말(띄어쓰기 없는 글자)에서 업종표 말을 찾는다 — 낱말 끝이거나 뒤에 의원·병원·점 같은 꼬리만 올 때. 가장 긴 말 */
const 꼬리 = /^(의원|병원|클리닉|센터|본점|지점|점|샵)?$/;
export function 낱말업종(token) {
  let 최고 = null;
  for (const x of 업종표) {
    for (const m of x.말) {
      let i = token.indexOf(m);
      while (i >= 0) {
        if (꼬리.test(token.slice(i + m.length)) && (!최고 || m.length > 최고.말.length)) 최고 = { 업종: x.업종, 말: m };
        i = token.indexOf(m, i + 1);
      }
    }
  }
  return 최고;
}

