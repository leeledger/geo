/**
 * 이름 판별 말 하나가 흔한가 — 남의 답에도 걸리는 말인가.
 * 이름에서 업종표 말·시도·시군구·「점」「본점」「지점」을 지운 나머지 한글이 2자 미만, 또는 말이 2자 이하.
 * 점이 든 말(도메인)과 한글이 없는 말은 여기서 판정하지 않는다(false) — 맨 영어 낱말은 자동으로 넣지 않는다(D223)
 */
export function 이름흔함(term) {
  const t = String(term ?? "").trim();
  if (t.includes(".") || !/[가-힣]/.test(t)) return false;
  if (t.replace(/\s+/g, "").length <= 2) return true;
  let 남음 = 낱말들(t).map((w) => {
    let x = w;
    for (const m of 지운말) x = x.split(m).join(" ");
    return x.split(" ").map((p) => p.replace(/(본점|지점|점)$/, "")).join("");
  }).join("");
  남음 = (남음.match(/[가-힣]/g) ?? []).length;
  return 남음 < 2;
}

