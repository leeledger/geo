/** 글 → 업종 후보 낱말 — 낱말 하나하나 + 이웃한 두 낱말을 붙인 것(「영어 학원」 → 「영어학원」) */
export const 업종낱말들 = (s) => { const w = 낱말들(s); return [...w, ...w.slice(1).map((x, i) => w[i] + x)]; };

