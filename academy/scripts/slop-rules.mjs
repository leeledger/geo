/**
 * AI 가 쓴 티 검사 규칙. CLI(slop-check.mjs)와 write-draft.mjs 가 같은 것을 부른다.
 *
 * 두 갈래로 나눈다.
 *   치명 — 하나라도 걸리면 초안이 원장 큐에 못 간다. 원장이 읽고 버리는 시간이 제일 비싸다
 *   경고 — 세기만 한다. 고칠지는 사람이 정한다
 *
 * 어휘만으로는 일반론을 못 잡는다. 그래서 「구체가 하나도 없는 문단」을 세고,
 * 「지어낸 장면」은 쓴 재료의 말과 겹치는지로 가른다. 재료에 없는 장면은 지어낸 것이다.
 */

/** 구체 명사 사전. 늘리기 쉽게 여기 둔다 — 새 교구·과목이 생기면 한 줄 더 넣는다 */
export const 지역 = ["송파", "잠실", "석촌", "가락", "헬리오", "문정", "위례", "방이"];
export const 교구 = [
  "스크래치", "엔트리", "아두이노", "파이썬", "마이크로비트", "라즈베리파이",
  "레고", "EV3", "정보올림피아드", "정보 교과", "알고리즘", "디버깅",
  "블록코딩", "블록 코딩", "피지컬컴퓨팅", "피지컬 컴퓨팅",
];

/** 잡을 것. 뒤에 왜 나쁜지를 적어 둔다 — 고칠 때 필요하다. */
export const MARKS = [
  { re: /알아보겠습니다|살펴보겠습니다|대해 알아보|소개해 드리겠습니다/g, why: "서론으로 여는 말" },
  // 연결어 하나는 문제가 아니다. "먼저 분명히 해둘 게 있습니다" 는 오히려 좋다.
  // 세트로 깔아서 순서를 만드는 게 AI 티다. 그래서 두 종류 이상일 때만 잡는다.
  { seq: ["먼저", "다음으로", "마지막으로", "끝으로"], min: 2, why: "순서를 까는 연결어 세트" },
  { re: /정말 중요|매우 중요|굉장히|너무나|아주 유용/g, why: "빈 강조" },
  { re: /라고 할 수 있습니다|인 것 같습니다|일 것입니다|하는 것이 좋습니다만/g, why: "흐린 마무리" },
  { re: /다양한|여러 가지|수많은|많은 분들/g, why: "숫자를 피하는 말" },
  { re: /놀라운|혁신적|필수적|완벽한|최적의|효과적으로/g, why: "과장 형용사" },
  { re: /장단점이 있|둘 다 맞|각각의 장점/g, why: "양비론" },
  { re: /요즘 많은|최근 들어 많은|바야흐로/g, why: "아무나 쓰는 도입" },
  // 「~것이 중요합니다」로 문단을 닫으면 판단이 아니라 훈계가 된다.
  // 금지 목록에는 적어 뒀는데 여기 정규식에 없어서 그냥 통과했다(2026-09-12).
  { re: /것이 현명합니다|것이 바람직합니다|것이 중요합니다|것이 좋습니다|도움이 됩니다/g, why: "훈계조로 닫기" },
];

/** 치명으로 올릴 기존 MARKS — [왜, 이 횟수부터] */
const 치명선 = { "서론으로 여는 말": 1, "훈계조로 닫기": 3 };

/**
 * 지어낸 장면 표시. 이 말이 든 문장은 쓴 재료에 근거가 있어야 한다.
 * 「한 학부모가」로 여는 문단이 원장이 버린 초안 셋에 다 있었다.
 */
const 장면표시 = [
  /한 (?:학부모|어머님|어머니|아버님|아버지)(?:가|께서|는|님)/,
  /어떤 (?:아이|학생|친구|학부모|어머님|아버님)(?:가|이|는)/,
  /(?:최근|얼마 전|지난주|지난달|며칠 전|작년|올해 초)\s*상담(?:에서|을|에)/,
  /한 번은 이런/,
  /수업 (?:중에|시간에) (?:한|어떤|어느)\s/,
];

/** 2인칭 훈계. 한 문단에 세 번 넘게 나오면 판단 기준이 아니라 설교다 */
const 훈계 = /하세요|해 보세요|권합니다|추천합니다|확인해 보시길/g;

const 숫자 = /\d/;
const 도메인 = /[a-z0-9-]+\.(?:kr|com|net|org|go\.kr|or\.kr|ac\.kr)/i;
const 인용부호 = /[「『"'"]/;

/** 문단으로 자른다. 소제목 줄은 뺀다 — 제목에 구체가 없는 건 흠이 아니다 */
export const 문단들 = (본문) =>
  본문
    .replace(/\r/g, "")
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter((p) => p && !/^#{1,4}\s/.test(p));

/** 문장으로 자른다. 한국어는 마침표를 빼먹는 일이 잦아 줄바꿈도 경계로 본다 */
export const 문장들 = (본문) =>
  본문
    .replace(/\r/g, "")
    .split(/(?<=[.!?…])\s+|\n+/)
    .map((s) => s.trim())
    .filter(Boolean);

/** b 의 n 자 이상 연속 부분이 a 안에 있나. 모델이 재료를 고쳐 쓰면 걸린다 — 그대로 인용해야 통과 */
export function 겹치나(a, b, n = 8) {
  const 원본 = (b ?? "").replace(/\s+/g, " ").trim();
  const 대상 = (a ?? "").replace(/\s+/g, " ");
  if (원본.length < n) return false;
  for (let i = 0; i + n <= 원본.length; i++) {
    if (대상.includes(원본.slice(i, i + n))) return true;
  }
  return false;
}

/** 이 문단에 구체가 하나라도 있나 */
export function 구체있나(문단) {
  if (숫자.test(문단)) return true;
  if (인용부호.test(문단)) return true;
  if (도메인.test(문단)) return true;
  if (지역.some((w) => 문단.includes(w))) return true;
  if (교구.some((w) => 문단.includes(w))) return true;
  return false;
}

/**
 * 본문을 검사한다.
 *   본문     마크다운 본문
 *   재료들   이 글에 쓴 재료 [{ said }]. 빈 배열이면 「재료 없이 쓴 글」로 본다
 * 돌려주는 것 { 치명: [{why, n, sample}], 경고: [{why, n, sample}] }
 */
export function 검사(본문 = "", { 재료들 = [] } = {}) {
  const 치명 = [];
  const 경고 = [];

  // ── 1. 지어낸 장면
  const 걸린문장 = [];
  for (const s of 문장들(본문)) {
    if (!장면표시.some((re) => re.test(s))) continue;
    // 쓴 재료가 하나도 없으면 근거가 있을 수 없다. 재료가 있으면 그 말이 이 문장에 그대로 들어 있어야 한다
    if (재료들.some((m) => 겹치나(s, m.said))) continue;
    걸린문장.push(s.slice(0, 60));
  }
  if (걸린문장.length) {
    치명.push({
      why: "지어낸 장면",
      n: 걸린문장.length,
      sample: 걸린문장.slice(0, 3),
      말: 재료들.length
        ? "상담·수업 장면을 썼는데 쓴 재료의 말과 겹치는 데가 없습니다. 재료에 있는 말만 씁니다"
        : "재료 없이 상담·수업 장면을 썼습니다. 원장이 실제로 들은 말만 씁니다",
    });
  }

  // ── 2. 일반론 문단
  const ps = 문단들(본문);
  const 일반론 = ps.filter((p) => p.length >= 120 && !구체있나(p));
  if (ps.length && 일반론.length / ps.length > 0.4) {
    치명.push({
      why: `일반론 문단 ${일반론.length}/${ps.length}`,
      n: 일반론.length,
      sample: 일반론.slice(0, 2).map((p) => `${p.slice(0, 50)}…`),
      말: "숫자·지역·교구·인용이 하나도 없는 문단이 절반 가까이입니다. 검색하면 아무나 쓸 수 있는 글입니다",
    });
  }

  // ── 3. 2인칭 훈계 덩어리
  const 설교 = ps.filter((p) => (p.match(훈계) ?? []).length >= 3);
  if (설교.length) {
    치명.push({
      why: "2인칭 훈계 덩어리",
      n: 설교.length,
      sample: 설교.slice(0, 2).map((p) => `${p.slice(0, 50)}…`),
      말: "한 문단에서 세 번 넘게 시킵니다. 판단 기준을 주고 끝냅니다",
    });
  }

  // ── 4. 기존 어휘 표시 — 치명선을 넘은 것만 치명, 나머지는 경고
  for (const m of MARKS) {
    let n = 0;
    let sample = [];
    if (m.seq) {
      const used = m.seq.filter((w) => new RegExp(`(^|\\n)\\s*${w}[,\\s]`).test(본문));
      if (used.length < m.min) continue;
      n = used.length;
      sample = used;
    } else {
      const hits = 본문.match(m.re);
      if (!hits) continue;
      n = hits.length;
      sample = [...new Set(hits)].slice(0, 3);
    }
    const 선 = 치명선[m.why];
    (선 !== undefined && n >= 선 ? 치명 : 경고).push({ why: m.why, n, sample });
  }

  return { 치명, 경고 };
}
